let currentLang = localStorage.getItem("lang") || "en";

// Recursive function to get translation from nested objects
function getTranslation(key, obj = translations[currentLang]) {
  if (!obj) return key;

  // direct key
  if (obj[key] !== undefined) return obj[key];

  // search nested objects (like products, machines, etc.)
  for (const k in obj) {
    if (typeof obj[k] === "object") {
      const res = getTranslation(key, obj[k]);
      if (res !== undefined) return res;
    }
  }

  return undefined; // fallback if not found
}

function applyTranslations(lang = currentLang) {
  currentLang = lang;

  // Translate elements with data-text
  document.querySelectorAll("[data-text]").forEach(el => {
    const translated = getTranslation(el.dataset.text);
    if (translated) el.textContent = translated;
  });

  // Translate placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const translated = getTranslation(el.dataset.i18nPlaceholder);
    if (translated) el.placeholder = translated;
  });

  // Optional: update <title>
  const titleEl = document.querySelector("title[data-i18n]");
  if (titleEl) {
    const translated = getTranslation(titleEl.dataset.i18n);
    if (translated) titleEl.textContent = translated;
  }

  localStorage.setItem("lang", currentLang);
}

